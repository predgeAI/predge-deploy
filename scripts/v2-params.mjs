// Computes per-chain v2 bond floors from live CoinGecko prices and writes config/v2.chains.json.
//   node scripts/v2-params.mjs [usdTarget=5]
// Floors are native wei, rounded to ONE significant digit, aiming at `usdTarget` dollars. The point of a floor
// is to stay above what a challenge costs in gas on that chain (v1 used 1e15 everywhere = $0.0002..$4).
// Review the output; the owner can change a floor later with setParams (it only affects future stakes).
import { writeFileSync } from "node:fs";
import { CHAINS } from "../lib/chains.mjs";

const usd = Number(process.argv[2] ?? 5);
const ids = [...new Set(Object.values(CHAINS).map((c) => c.coingecko))];
const r = await fetch(`https://api.coingecko.com/api/v3/simple/price?ids=${ids.join(",")}&vs_currencies=usd`, { signal: AbortSignal.timeout(20000) });
const prices = await r.json();
const oneSig = (wei) => { const s = wei.toString(); return BigInt(s[0] + "0".repeat(s.length - 1)) ; };
const out = { _comment: "Generated by scripts/v2-params.mjs. minBond / arbiterMinBond in native wei (18 decimals), ~usdTarget dollars each, 1 significant digit.", generatedAt: new Date().toISOString(), usdTarget: usd, chains: {} };
for (const [name, c] of Object.entries(CHAINS)) {
  const p = prices[c.coingecko]?.usd;
  if (!p) throw new Error(`no price for ${c.coingecko}`);
  const wei = oneSig(BigInt(Math.round((usd / p) * 1e6)) * 10n ** 12n);
  out.chains[name] = { native: c.native, priceUsd: p, minBond: wei.toString(), arbiterMinBond: wei.toString() };
}
writeFileSync(new URL("../config/v2.chains.json", import.meta.url), JSON.stringify(out, null, 2) + "\n");
console.log(Object.entries(out.chains).map(([k, v]) => `${k.padEnd(10)} ${v.minBond.padStart(24)} ${v.native} @ $${v.priceUsd}`).join("\n"));
